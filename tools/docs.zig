//! Writes the packet reference and IDE stubs from protocol-zig's types, the same ones the PHP bridge walks.
const std = @import("std");
const protocol = @import("bedwire").protocol;

const Packet = protocol.typed.Packet;
const Kind = protocol.PacketKind;

pub fn main(init: std.process.Init) !void {
    const args = try init.minimal.args.toSlice(init.arena.allocator());
    if (args.len != 3) return error.Usage;
    const io = init.io;
    const cwd = std.Io.Dir.cwd();

    var reference: std.Io.Writer.Allocating = .init(init.gpa);
    defer reference.deinit();
    try writeReference(&reference.writer);
    try cwd.writeFile(io, .{ .sub_path = args[1], .data = reference.written() });

    var stub: std.Io.Writer.Allocating = .init(init.gpa);
    defer stub.deinit();
    try writeStub(&stub.writer);
    try cwd.writeFile(io, .{ .sub_path = args[2], .data = stub.written() });
}

fn isList(comptime T: type) bool {
    return @typeInfo(T) == .@"struct" and @hasDecl(T, "Element") and @hasDecl(T, "iterator");
}

fn isBitset(comptime T: type) bool {
    return @typeInfo(T) == .@"struct" and @hasDecl(T, "isSet") and @hasDecl(T, "len");
}

fn shortName(comptime T: type) []const u8 {
    @setEvalBranchQuota(100_000);
    const full = @typeName(T);
    const dot = std.mem.lastIndexOfScalar(u8, full, '.') orelse return full;
    return full[dot + 1 ..];
}

/// The PHP value a field takes, mirroring src/php/packet.zig.
fn phpType(comptime T: type) []const u8 {
    return switch (@typeInfo(T)) {
        .void => "null",
        .bool => "bool",
        .int => "int",
        .float => "float",
        .@"enum" => "int",
        .optional => |info| "?" ++ phpType(info.child),
        .pointer => |info| if (info.child == u8) "string" else "list<" ++ phpType(info.child) ++ ">",
        .array => |info| if (info.child == u8) std.fmt.comptimePrint("string({d})", .{info.len}) else std.fmt.comptimePrint("list<{s}>({d})", .{ phpType(info.child), info.len }),
        .@"struct" => if (comptime isBitset(T))
            std.fmt.comptimePrint("string({d} bits)", .{T.len})
        else if (comptime isList(T))
            "list<" ++ phpType(T.Element) ++ ">"
        else
            "[" ++ shortName(T) ++ "](#" ++ anchor(shortName(T)) ++ ")",
        .@"union" => "[" ++ shortName(T) ++ "](#" ++ anchor(shortName(T)) ++ ")",
        else => @compileError("unsupported " ++ @typeName(T)),
    };
}

fn anchor(comptime name: []const u8) []const u8 {
    comptime {
        @setEvalBranchQuota(100_000);
        var out: [name.len]u8 = undefined;
        for (name, 0..) |byte, i| out[i] = std.ascii.toLower(byte);
        const final = out;
        return &final;
    }
}

const nested: []const type = blk: {
    @setEvalBranchQuota(10_000_000);
    var seen: []const type = &.{};
    for (@typeInfo(Packet).@"union".field_types) |P| for (@typeInfo(P).@"struct".field_types) |F| collect(F, &seen);
    break :blk seen;
};

fn collect(comptime T: type, comptime seen: *[]const type) void {
    switch (@typeInfo(T)) {
        .optional => |info| collect(info.child, seen),
        .pointer => |info| collect(info.child, seen),
        .array => |info| collect(info.child, seen),
        .@"struct" => |info| {
            if (isBitset(T)) return;
            if (isList(T)) return collect(T.Element, seen);
            for (seen.*) |known| if (known == T) return;
            seen.* = seen.* ++ .{T};
            for (info.field_types) |F| collect(F, seen);
        },
        .@"union" => |info| {
            for (seen.*) |known| if (known == T) return;
            seen.* = seen.* ++ .{T};
            for (info.field_types) |F| collect(F, seen);
        },
        else => {},
    }
}

fn writeFields(writer: *std.Io.Writer, comptime T: type) !void {
    const info = @typeInfo(T).@"struct";
    if (info.field_names.len == 0) return writer.writeAll("No fields: pass `[]`.\n\n");
    try writer.writeAll("| Field | PHP type |\n| --- | --- |\n");
    inline for (info.field_names, info.field_types) |name, F| try writer.print("| `{s}` | {s} |\n", .{ name, comptime phpType(F) });
    try writer.writeAll("\n");
}

fn writeReference(writer: *std.Io.Writer) !void {
    try writer.print(
        \\# Packet reference
        \\
        \\Generated by `zig build docs` from protocol-zig for protocol {d} (Minecraft {s}). Do not edit.
        \\
        \\`Bedwire\Protocol::decode()` returns, and `encode()` takes, the fields below as an array keyed by field name.
        \\Nested structs are arrays keyed the same way, a union is an array with exactly one key naming the variant,
        \\lists are PHP lists, enums are ints, optional fields may be `null` or left out, and NBT fields hold raw network NBT
        \\(read them with `Bedwire\Nbt::read($bytes, Nbt::NETWORK)`). 64-bit unsigned values wrap into PHP's signed int.
        \\
        \\## Packets
        \\
        \\
    , .{ protocol.protocol_version, protocol.minecraft_version });

    inline for (@typeInfo(Kind).@"enum".field_names) |name| {
        const kind = @field(Kind, name);
        const direction = switch (protocol.registry.packetDirection(kind)) {
            .client_to_server => "serverbound",
            .server_to_client => "clientbound",
            .bidirectional => "both directions",
        };
        try writer.print("### {s}\n\n`PacketId::{s}` = {d}, {s}.\n\n", .{ name, comptime upper(name), protocol.registry.packetId(kind).?, direction });
        try writeFields(writer, @FieldType(Packet, name));
    }

    try writer.writeAll("## Types\n\n");
    inline for (nested) |T| {
        try writer.print("### {s}\n\n", .{shortName(T)});
        switch (@typeInfo(T)) {
            .@"struct" => try writeFields(writer, T),
            .@"union" => |info| {
                try writer.writeAll("One of:\n\n| Variant | PHP type |\n| --- | --- |\n");
                inline for (info.field_names, info.field_types) |name, F| try writer.print("| `{s}` | {s} |\n", .{ name, comptime phpType(F) });
                try writer.writeAll("\n");
            },
            else => unreachable,
        }
    }
}

fn upper(comptime name: []const u8) []const u8 {
    comptime {
        @setEvalBranchQuota(100_000);
        var out: [name.len]u8 = undefined;
        for (name, 0..) |byte, i| out[i] = std.ascii.toUpper(byte);
        const final = out;
        return &final;
    }
}

fn writeStub(writer: *std.Io.Writer) !void {
    try writer.print(
        \\<?php
        \\
        \\// Generated by `zig build docs` for IDEs and static analysis. The extension registers these at startup.
        \\
        \\namespace Bedwire;
        \\
        \\final class Protocol
        \\{{
        \\    public const int VERSION = {d};
        \\    public const string MINECRAFT_VERSION = "{s}";
        \\}}
        \\
        \\final class PacketId
        \\{{
        \\
    , .{ protocol.protocol_version, protocol.minecraft_version });
    inline for (@typeInfo(Kind).@"enum".field_names) |name| {
        try writer.print("    public const int {s} = {d};\n", .{ comptime upper(name), protocol.registry.packetId(@field(Kind, name)).? });
    }
    try writer.writeAll("}\n");
}
